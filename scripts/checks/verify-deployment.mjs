import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import vm from 'node:vm';
import { pathToFileURL } from 'node:url';
const root = path.resolve(import.meta.dirname, '../..');
const dest = path.join(root, '.runtime/node_modules/@kaczev/dsh-provider-line-failover');
fs.mkdirSync(dest, { recursive: true });
fs.cpSync(path.join(root, 'plugin'), dest, { recursive: true });
const sha = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
assert.equal(sha(path.join(root, 'plugin/client.js')), sha(path.join(dest, 'client.js')));
const meta = JSON.parse(fs.readFileSync(path.join(dest, 'package.json')));
assert.equal(meta.engines.dsh, '0.2.1-rc.3');
assert.equal(meta.exports['./client'], './client.js');
assert.equal(meta.dsh.client.platform, 'web');
for (const file of ['index.js', 'client.js', 'cordis.patch.yml', 'icon.svg', 'locale/en.json', 'locale/zh-CN.json']) assert.ok(fs.statSync(path.join(dest, file)).isFile());
const plugin = await import(pathToFileURL(path.join(dest, 'index.js')));
let configured = false;
await assert.rejects(plugin.apply({ configEditor: { entries: () => [] }, effect(callback) { callback(); }, settings: { configure(value) { assert.equal(value.auto, false); configured = true; return () => {}; } } }, {}), /PiAiAdapter module unavailable/);
assert.ok(configured);
let definition, registration;
vm.runInNewContext(fs.readFileSync(path.join(dest, 'client.js'), 'utf8'), { window: { __ModuleLoader__: { load(value) { definition = value; } } }, URL });
const client = definition.factory(() => ({ createElement() {} }));
client.apply({ slots: { inject(name, callback) { assert.equal(name, 'settings.section'); callback(); }, register(value) { registration = value; } } });
assert.equal(registration.id, 'kaczev-provider-line-failover');
assert.ok(fs.statSync(path.join(dest, 'transport.js')).isFile());
console.log('PASS copied rc3 bundle metadata/resources, host policy, independent client registration; no core apply or Desktop changes');
console.log('LIMIT: this is an isolated package check, not proof of Desktop deployment or transport failover');
